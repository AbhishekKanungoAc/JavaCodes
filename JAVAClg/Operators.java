package JAVAClg;
/*operators */
public class Operators {
    public static void main(String[] args) {
        /*Ar. op. */
        System.out.println("10+20:"+(10+20));
        System.out.println("10%20:"+(10%20));//reminder
        System.out.println("10-20:"+(10-20));
        System.out.println("10*20:"+(10*20));
        System.out.println("10/20:"+(10/20));//qosnt

        /* relational op */
        System.out.println("eql 10==20:"+(10==20));

        /*logical op */
        System.out.println("10<5 && 10<10:"+(10<5 && 10<10));
        System.out.println("!10<5 && 10<10:"+(!(10<5 && 10<10)));
        

    }
}
