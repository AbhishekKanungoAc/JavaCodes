package JAVAClg;
/*data type examples */
public class DataType {
    public static void main(String[] args) {
        float f = 10.5f;
        double d = 10.5;
        char c = 'A';
        boolean b = true;
        System.out.println("float:"+f);
        System.out.println("double:"+d);
        System.out.println("char:"+c);
        System.out.println("boolen:"+b);
    }
}
